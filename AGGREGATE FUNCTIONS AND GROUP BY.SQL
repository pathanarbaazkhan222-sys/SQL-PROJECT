-- AGGREGATE FUNCTIONS AND GROUP BY


--Count total number of transactions
SELECT COUNT(*) AS TOTAL_TRANSACTIONS
FROM SALES_TRANSACTIONS;


--Calculate total quantity sold
SELECT SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD
FROM SALES_TRANSACTIONS;


--Calculate average unit price
SELECT ROUND(AVG(UNIT_PRICE), 2) AS AVERAGE_UNIT_PRICE
FROM SALES_TRANSACTIONS;


--Find highest unit price
SELECT MAX(UNIT_PRICE) AS HIGHEST_UNIT_PRICE
FROM SALES_TRANSACTIONS;


--Find lowest unit price
SELECT MIN(UNIT_PRICE) AS LOWEST_UNIT_PRICE
FROM SALES_TRANSACTIONS;


--Calculate total sales
SELECT SUM(QUANTITY * UNIT_PRICE) AS TOTAL_SALES
FROM SALES_TRANSACTIONS;


--Calculate total sales by city
SELECT CITY,
       SUM(QUANTITY * UNIT_PRICE) AS TOTAL_SALES
FROM SALES_TRANSACTIONS
GROUP BY CITY
ORDER BY TOTAL_SALES DESC;


--Calculate total quantity sold by product
SELECT PRODUCT_NAME,
       SUM(QUANTITY) AS TOTAL_QUANTITY
FROM SALES_TRANSACTIONS
GROUP BY PRODUCT_NAME
ORDER BY TOTAL_QUANTITY DESC;


--Count transactions by payment mode
SELECT PAYMENT_MODE,
       COUNT(*) AS TOTAL_TRANSACTIONS
FROM SALES_TRANSACTIONS
GROUP BY PAYMENT_MODE
ORDER BY TOTAL_TRANSACTIONS DESC;


--Find average unit price by city
SELECT CITY,
       ROUND(AVG(UNIT_PRICE), 2) AS AVERAGE_UNIT_PRICE
FROM SALES_TRANSACTIONS
GROUP BY CITY
ORDER BY AVERAGE_UNIT_PRICE DESC;


--Find cities with total sales greater than 10000
SELECT CITY,
       SUM(QUANTITY * UNIT_PRICE) AS TOTAL_SALES
FROM SALES_TRANSACTIONS
GROUP BY CITY
HAVING SUM(QUANTITY * UNIT_PRICE) > 10000
ORDER BY TOTAL_SALES DESC;


--Find products with total quantity sold greater than 10
SELECT PRODUCT_NAME,
       SUM(QUANTITY) AS TOTAL_QUANTITY
FROM SALES_TRANSACTIONS
GROUP BY PRODUCT_NAME
HAVING SUM(QUANTITY) > 10
ORDER BY TOTAL_QUANTITY DESC;
